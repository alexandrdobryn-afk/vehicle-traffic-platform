type Params = Record<string, string | number>

type I18nContextValue = {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: (key: string, params?: Params) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function interpolate(value: string, params?: Params) {
  if (!params) return value
  return Object.entries(params).reduce(
    (text, [key, replacement]) => text.replaceAll(`{${key}}`, String(replacement)),
    value,
  )
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en')

  useEffect(() => {
    const saved = localStorage.getItem('vtp-language')
    if (saved === 'uk' || saved === 'en') setLanguageState(saved)
  }, [])

  useEffect(() => {
    document.documentElement.lang = language === 'uk' ? 'uk' : 'en'
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language === 'uk' ? 'uk-UA' : 'en-US',
    setLanguage: (next) => {
      setLanguageState(next)
      localStorage.setItem('vtp-language', next)
    },
    t: (key, params) => interpolate(language === 'uk' ? (uk[key] || key) : key, params),
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useTranslation() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useTranslation must be used inside LanguageProvider')
  return value
}
